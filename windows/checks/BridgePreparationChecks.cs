    }

    private static async Task BoundedAndShared()
    {
        using (Fixture server = new Fixture())
        using (BridgePreparation prep = New(server, "bounded"))
        {
            var items = Enumerable.Range(1, 5).Select(i => Item(i)).ToArray();
            prep.UpdateItems(items);
            Check(prep.GetStatus(items[0]).State == BridgePreparationState.Pending && server.Requests == 0,
                "Reading pending status performs no networking");
            var progress = new ProgressCapture();
            Task<string[]> first = prep.PrepareAsync(items, progress, CancellationToken.None);
            Task<string[]> second = prep.PrepareAsync(items, null, CancellationToken.None);
            await Until(delegate { return server.Requests == 2; });
            await Task.Delay(100);
            string[] paths;
            Check(server.Requests == 2 && !prep.TryGetReady(items, out paths) &&
                items.Count(i => prep.GetStatus(i).State == BridgePreparationState.Preparing) == 2,
                "Five selected files and overlapping callers start only two workers and never advertise pending paths");
            server.Release.TrySetResult(true);
            string[] a = await Finish(first), b = await Finish(second);
            Check(a.SequenceEqual(b) && a.Length == 5 && server.Requests == 5 && server.MaximumActive <= 2,
                "Overlapping selections single-flight each version with at most two active HTTP requests");
            Check(prep.TryGetReady(items, out paths) && paths.SequenceEqual(a) &&
                paths.All(p => File.ReadAllBytes(p).SequenceEqual(Body)) && !Directory.GetFiles(root, "*.part", SearchOption.AllDirectories).Any(),
                "Only complete verified generated bytes become ready; no partial file remains");
            BridgePreparationProgress final = progress.Last;
            Check(final != null && final.Bytes == 25 && final.TotalBytes == 25 && final.CompletedItems == 5 && final.TotalItems == 5,
                "Aggregate progress reports exact byte and completion totals");
            int requests = server.Requests;
            Check((await Finish(prep.PrepareAsync(items, null, CancellationToken.None))).SequenceEqual(a) && server.Requests == requests,
                "Repeated preparation reuses completed snapshots without another request");
            prep.CancelSession();
            Check(!prep.TryGetReady(items, out paths) && a.All(File.Exists),
                "Ended sessions revoke drag readiness while retaining complete source files for cache grace");
        }
    }

    private static async Task ChangedVersions()
    {
        using (Fixture server = new Fixture())
        using (BridgePreparation prep = New(server, "versions"))
        {
            BridgeItem old = Item(1), changed = Item(1); changed.Modified++; changed.Name = "new-name.txt";
            prep.UpdateItems(new[] { old });
            Task<string[]> downloading = prep.PrepareAsync(new[] { old }, null, CancellationToken.None);
            await Until(delegate { return server.Requests == 1; });
            prep.UpdateItems(new[] { changed });
            await Reject<OperationCanceledException>(downloading);
            Check(prep.GetStatus(old).State == BridgePreparationState.Failed && prep.GetStatus(changed).State == BridgePreparationState.Pending,
                "A changed version cancels its in-flight predecessor and reports the replacement as pending");
            await Reject<IOException>(prep.PrepareAsync(new[] { old }, null, CancellationToken.None));
            int requests = server.Requests;
            Check(requests == 1, "A revoked old selection cannot restart a network download");
            server.Release.TrySetResult(true);
            string[] paths = await Finish(prep.PrepareAsync(new[] { changed }, null, CancellationToken.None));
            Check(Path.GetFileName(paths[0]) == changed.Name && server.Requests == 2,
                "The replacement version receives a fresh private file and its new filename");
            prep.UpdateItems(new BridgeItem[0]);
            string[] ignored;
            Check(!prep.TryGetReady(new[] { changed }, out ignored) && File.Exists(paths[0]),
                "An empty phone shelf invalidates completed readiness without deleting an offered source");
        }
    }

    private static async Task CallerCancellation()
    {
        using (Fixture server = new Fixture())
        using (BridgePreparation prep = New(server, "caller-cancel"))
        using (CancellationTokenSource caller = new CancellationTokenSource())
        {
            BridgeItem item = Item(1);
            Task<string[]> first = prep.PrepareAsync(new[] { item }, null, caller.Token);
            Task<string[]> survivor = prep.PrepareAsync(new[] { item }, null, CancellationToken.None);
            await Until(delegate { return server.Requests == 1; });
            caller.Cancel();
            await Reject<OperationCanceledException>(first);
            Check(!survivor.IsCompleted && server.Requests == 1,
                "Cancelling one caller promptly stops its wait without cancelling another caller's shared transfer");
            server.Release.TrySetResult(true);
            Check(File.Exists((await Finish(survivor))[0]) && server.Requests == 1,
                "A surviving caller finishes the original single-flight download");
        }
    }

    private static async Task SessionCancellation()
    {
        using (Fixture server = new Fixture())
        using (CancellationTokenSource session = new CancellationTokenSource())
        {
            int uses = 0, acquires = 0, releases = 0;
            string cache = Path.Combine(root, "session-cancel");
            using (BridgePreparation prep = new BridgePreparation(new DockBridgeClient(server.Port, Token),
                delegate(BridgeItem item) { return cache; },
                delegate { Interlocked.Increment(ref uses); Interlocked.Increment(ref acquires); return new OnDispose(delegate { Interlocked.Decrement(ref uses); Interlocked.Increment(ref releases); }); }, session.Token))
            {
                BridgeItem[] items = Enumerable.Range(1, 4).Select(i => Item(i)).ToArray();
                Task<string[]> all = prep.PrepareAsync(items, null, CancellationToken.None);
                await Until(delegate { return server.Requests == 2 && Volatile.Read(ref uses) == 2; });
                Stopwatch elapsed = Stopwatch.StartNew(); session.Cancel();
                await Reject<OperationCanceledException>(all);
                await Until(delegate { return Volatile.Read(ref uses) == 0; });
                Check(elapsed.ElapsedMilliseconds < 2500 && server.Requests == 2 && acquires == 2 && releases == 2,
                    "Session cancellation aborts stalled sockets, skips queued files, and releases both active cache uses promptly");
                Check(!Directory.GetFiles(cache, "*.part", SearchOption.AllDirectories).Any(),
                    "Cancelled downloads clean their private partial files before cache-use release");
                server.Release.TrySetResult(true);
            }
        }
    }

    private static async Task FailedAndRetry()
    {
        using (Fixture server = new Fixture())
        using (BridgePreparation prep = New(server, "failure"))
        {
            server.Release.TrySetResult(true); server.Status = "403 Forbidden";
            BridgeItem item = Item(1);
            await Reject<IOException>(prep.PrepareAsync(new[] { item }, null, CancellationToken.None));
            string[] paths;
            Check(prep.GetStatus(item).State == BridgePreparationState.Failed && !String.IsNullOrEmpty(prep.GetStatus(item).Error) &&
                !prep.TryGetReady(new[] { item }, out paths), "A refused or revoked peer produces actionable failure and never a ready path");
            server.Status = "200 OK";
            paths = await Finish(prep.PrepareAsync(new[] { item }, null, CancellationToken.None));
            Check(File.Exists(paths[0]) && server.Requests == 2, "An explicit retry after peer recovery creates a new successful flight");
            BridgeItem truncated = Item(2); server.SentBody = new byte[] { 1, 2 };
            await Reject<IOException>(prep.PrepareAsync(new[] { truncated }, null, CancellationToken.None));
            Check(!prep.TryGetReady(new[] { truncated }, out paths) && !Directory.GetFiles(root, "*.part", SearchOption.AllDirectories).Any(),
                "Premature EOF remains failed and never exposes or retains a partial file");
        }
    }

    private static async Task NamesAndLocalChanges()
    {
        using (Fixture server = new Fixture())
        using (BridgePreparation prep = New(server, "names"))
        {
            server.Release.TrySetResult(true);
            BridgeItem first = Item(1), duplicate = Item(2), empty = Item(3), reserved = Item(4);
            first.Name = duplicate.Name = "文件-é-😀.txt"; empty.Name = "empty.txt"; empty.Size = 0; reserved.Name = "CON.txt";
            BridgeItem[] items = new[] { first, duplicate, empty, reserved };
            server.EmptyId = empty.Id;
            string[] paths = await Finish(prep.PrepareAsync(items, null, CancellationToken.None));
            Check(paths.Distinct(StringComparer.OrdinalIgnoreCase).Count() == 4 && Path.GetFileName(paths[0]) == first.Name &&
                Path.GetFileName(paths[1]) == duplicate.Name && Path.GetFileName(paths[3]) == "_CON.txt" && new FileInfo(paths[2]).Length == 0,
                "Unicode names, duplicate leaf names, reserved Windows names and zero-byte files are safe isolated snapshots");
            byte[] original = File.ReadAllBytes(paths[0]);
            File.AppendAllText(paths[0], "changed");
            string[] ignored;
            Check(!prep.TryGetReady(new[] { first }, out ignored) && prep.GetStatus(first).State == BridgePreparationState.Failed,
                "A locally changed ready file immediately loses readiness");
            string replacement = (await Finish(prep.PrepareAsync(new[] { first }, null, CancellationToken.None)))[0];
            Check(replacement != paths[0] && File.ReadAllBytes(replacement).SequenceEqual(original) && File.ReadAllText(paths[0]).EndsWith("changed"),
                "Retry creates a new private file and never overwrites a changed local copy");
            DateTime stamp = File.GetLastWriteTimeUtc(replacement);
            File.WriteAllBytes(replacement, new byte[] { 9, 8, 7, 6, 5 }); File.SetLastWriteTimeUtc(replacement, stamp.AddSeconds(2));
            Check(!prep.TryGetReady(new[] { first }, out ignored), "Same-length changes with a new write stamp also invalidate readiness");
            string ready = paths[1]; File.Delete(ready);
            Check(!prep.TryGetReady(new[] { duplicate }, out ignored), "A removed local copy cannot be offered to Windows");
        }
    }

    private static async Task IdleDeadlines()
    {
        using (Fixture server = new Fixture())
        {
            server.PrefixBytesBeforeStall = 1;
            var client = new DockBridgeClient(server.Port, Token, 250);
            string cache = Path.Combine(root, "idle-body");
            using (var prep = new BridgePreparation(client, cache, CancellationToken.None))
            {
                BridgeItem item = Item(1);
                Stopwatch elapsed = Stopwatch.StartNew();
                Task<string[]> stalled = prep.PrepareAsync(new[] { item }, null, CancellationToken.None);
                await Until(delegate { return server.Requests == 1; });
                for (int i = 0; i < 3; i++)
                {
                    await Task.Delay(30);
                    BridgeStatus status = await client.GetStatusAsync(CancellationToken.None);
                    if (status.Version != 1) throw new Exception("Generated status fixture was unhealthy.");
                }
                await Reject<TimeoutException>(stalled);
                Check(elapsed.ElapsedMilliseconds < 2500 && server.StatusRequests == 3 &&
                    prep.GetStatus(item).State == BridgePreparationState.Failed && prep.GetStatus(item).Error.Contains("stopped responding") &&
                    !Directory.GetFiles(cache, "*.part", SearchOption.AllDirectories).Any(),
                    "A partially received file times out on its idle clock despite healthy status responses, removes its partial and reports an actionable failure");
                server.PrefixBytesBeforeStall = 0; server.Release.TrySetResult(true);
                Check(File.Exists((await Finish(prep.PrepareAsync(new[] { item }, null, CancellationToken.None)))[0]) && server.Requests == 2,
                    "Idle expiry releases the worker so an explicit retry succeeds after the peer recovers");
            }
        }
        using (Fixture server = new Fixture())
        {
            server.WaitBeforeHeaders = true;
            var client = new DockBridgeClient(server.Port, Token, 200);
            await Reject<TimeoutException>(client.DownloadAsync(Item(1), Path.Combine(root, "idle-headers"), null, CancellationToken.None));
            Check(server.Requests == 1, "The idle deadline also bounds waiting for response headers");
        }
        using (Fixture server = new Fixture())
        {
            server.Release.TrySetResult(true); server.BodyChunkDelayMs = 120;
            var client = new DockBridgeClient(server.Port, Token, 350);
            Stopwatch elapsed = Stopwatch.StartNew();
            string path = await Finish(client.DownloadAsync(Item(1), Path.Combine(root, "idle-reset"), null, CancellationToken.None));
            Check(elapsed.ElapsedMilliseconds >= 400 && File.ReadAllBytes(path).SequenceEqual(Body),
                "Regular incoming chunks reset the idle clock and permit a transfer lasting longer than one idle interval");
        }
        using (Fixture server = new Fixture())
        using (CancellationTokenSource caller = new CancellationTokenSource())
        {
            var client = new DockBridgeClient(server.Port, Token, 1000);
            Task<string> transfer = client.DownloadAsync(Item(1), Path.Combine(root, "idle-caller-cancel"), null, caller.Token);
            await Until(delegate { return server.Requests == 1; }); caller.Cancel();
            await Reject<OperationCanceledException>(transfer);
            Check(!Directory.GetFiles(Path.Combine(root, "idle-caller-cancel"), "*.part", SearchOption.AllDirectories).Any(),
                "Explicit cancellation remains cancellation rather than an idle timeout and cleans its partial");
        }
    }

    private static async Task IndependentSessions()
