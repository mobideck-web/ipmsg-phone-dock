    private static async Task LongSourcePaths()
    {
        using (Fixture server = new Fixture())
        {
            server.Release.TrySetResult(true);
            string parent = Path.Combine(root, "nested-cache");
            string wrapper = Path.Combine(parent, new String('c', Math.Max(1, 170 - parent.Length - 1)));
            BridgeItem item = Item(1); item.Name = String.Concat(Enumerable.Repeat("😀", 240)) + ".binfile";
            using (var prep = new BridgePreparation(new DockBridgeClient(server.Port, Token), wrapper, CancellationToken.None))
            {
                string expected = VirtualFileDrag.ExportNameForDirectory(item.Name, Path.Combine(wrapper, "bridge-" + new String('0', 32)));
                string path = (await Finish(prep.PrepareAsync(new[] { item }, null, CancellationToken.None)))[0];
                string leaf = Path.GetFileName(path);
                bool validPairs = true;
                for (int i = 0; i < leaf.Length; i++)
                {
                    if (!Char.IsSurrogate(leaf[i])) continue;
                    if (!Char.IsHighSurrogate(leaf[i]) || i + 1 >= leaf.Length || !Char.IsLowSurrogate(leaf[++i])) { validPairs = false; break; }
                }
                Check(path.Length <= 240 && leaf == expected && leaf.EndsWith(".binfile", StringComparison.Ordinal) &&
                    validPairs && File.ReadAllBytes(path).SequenceEqual(Body),
                    "A 488-character Unicode filename under nested cache directories fits the 240-character Shell path budget and preserves extension/surrogate pairs");
            }
            foreach (int length in new[] { 205, 300 })
            {
                string tooLong = Path.Combine(root, new String('r', Math.Max(1, length - root.Length - 1)));
                using (var prep = new BridgePreparation(new DockBridgeClient(server.Port, Token), tooLong, CancellationToken.None))
                {
                    int before = server.Requests;
                    await Reject<IOException>(prep.PrepareAsync(new[] { Item(2) }, null, CancellationToken.None));
                    Check(server.Requests == before && !Directory.Exists(tooLong) && prep.GetStatus(Item(2)).Error.Contains("shorter local data folder"),
                        "A " + length + "-character cache root fails actionably before directory creation or networking");
                }
            }
        }
    }

