    private static async Task FolderPreparation()
    {
        byte[] archive;
        using (MemoryStream memory = new MemoryStream())
        {
            using (ZipArchive zip = new ZipArchive(memory, ZipArchiveMode.Create, true, Encoding.UTF8))
            {
                zip.CreateEntry("empty/");
                using (Stream output = zip.CreateEntry("nested/file.txt").Open()) output.Write(Body, 0, Body.Length);
            }
            archive = memory.ToArray();
        }
        using (Fixture server = new Fixture())
        using (var prep = new BridgePreparation(new DockBridgeClient(server.Port, Token),
            delegate(BridgeItem ignored) { return Path.Combine(root, "folder-downloads"); },
            delegate(BridgeItem ignored) { return Path.Combine(root, "folder-" + Guid.NewGuid().ToString("N")); }, null, CancellationToken.None))
        {
            server.Release.TrySetResult(true); server.SentBody = archive; server.AdvertisedLength = archive.Length;
            BridgeItem item = Item(1); item.Name = "Phone album.zip"; item.Mime = FolderSnapshot.Mime; item.Size = archive.Length;
            prep.UpdateItems(new[] { item });
            string path = (await Finish(prep.PrepareAsync(new[] { item }, null, CancellationToken.None)))[0];
            string[] ready;
            Check(Directory.Exists(path) && Path.GetFileName(path) == "Phone album" && Directory.Exists(Path.Combine(path, "empty")) &&
                File.ReadAllBytes(Path.Combine(path, "nested", "file.txt")).SequenceEqual(Body) && prep.TryGetReady(new[] { item }, out ready) && ready[0] == path,
                "A folder archive is downloaded and safely materialized before its real directory becomes drag-ready");
            Check(!Directory.GetFiles(Path.Combine(root, "folder-downloads"), "*.zip", SearchOption.AllDirectories).Any(),
                "A materialized folder does not retain a second archive throughout cache grace");
            prep.UpdateItems(new BridgeItem[0]);
            Check(!prep.TryGetReady(new[] { item }, out ready) && Directory.Exists(path),
                "Revoking a ready folder immediately removes drag permission while preserving the prior drop source for its cache lease");
        }
        using (Fixture server = new Fixture())
        using (var prep = New(server, "bad-folder"))
        {
            server.Release.TrySetResult(true);
            BridgeItem item = Item(2); item.Name = "Invalid.zip"; item.Mime = FolderSnapshot.Mime;
            await Reject<IOException>(prep.PrepareAsync(new[] { item }, null, CancellationToken.None));
            string[] ignored;
            Check(!prep.TryGetReady(new[] { item }, out ignored) && prep.GetStatus(item).State == BridgePreparationState.Failed &&
                !Directory.GetFiles(Path.Combine(root, "bad-folder"), "*.zip", SearchOption.AllDirectories).Any(),
                "An invalid folder archive stays failed and its disposable ZIP is cleaned before another retry");
        }
        using (Fixture server = new Fixture())
        using (var prep = New(server, "ordinary-zip"))
        {
            server.Release.TrySetResult(true); server.SentBody = archive; server.AdvertisedLength = archive.Length;
            BridgeItem item = Item(3); item.Name = "Ordinary.zip"; item.Mime = "application/zip"; item.Size = archive.Length;
            string path = (await Finish(prep.PrepareAsync(new[] { item }, null, CancellationToken.None)))[0];
            Check(File.Exists(path) && File.ReadAllBytes(path).SequenceEqual(archive), "An ordinary selected ZIP remains a file and is never extracted implicitly");
        }
    }

    private static BridgePreparation New(Fixture server, string folder)
    { return new BridgePreparation(new DockBridgeClient(server.Port, Token), Path.Combine(root, folder), CancellationToken.None); }
    private static readonly byte[] Body = new byte[] { 0, 1, 2, 127, 255 };
    private static BridgeItem Item(int number)
    { return new BridgeItem { Id = number.ToString("x32"), Name = "file-" + number + ".bin", Mime = "application/octet-stream", Size = 5, Modified = 1700000000000 }; }
    private static void Check(bool condition, string message)
    { if (!condition) throw new Exception("FAIL: " + message); Console.WriteLine("PASS " + (++passed) + ": " + message); }
    private static async Task Until(Func<bool> condition)
    {
        Stopwatch elapsed = Stopwatch.StartNew();
        while (!condition()) { if (elapsed.ElapsedMilliseconds > 5000) throw new TimeoutException("Fixture condition was not reached."); await Task.Delay(10); }
    }
    private static async Task<T> Finish<T>(Task<T> task)
    { if (await Task.WhenAny(task, Task.Delay(5000)) != task) throw new TimeoutException("Preparation exceeded five seconds."); return await task; }
    private static async Task Reject<T>(Task task) where T : Exception
    {
        if (await Task.WhenAny(task, Task.Delay(5000)) != task) throw new TimeoutException("Failure exceeded five seconds.");
        try { await task; } catch (T) { return; } throw new Exception("Expected " + typeof(T).Name);
    }
    private sealed class ProgressCapture : IProgress<BridgePreparationProgress>
    { public BridgePreparationProgress Last; public void Report(BridgePreparationProgress value) { Last = value; } }
    private sealed class OnDispose : IDisposable
    { private readonly Action action; internal OnDispose(Action value) { action = value; } public void Dispose() { action(); } }

    private sealed class Fixture : IDisposable
    {
        private readonly TcpListener listener;
        public readonly TaskCompletionSource<bool> Release = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
        public int Port, Requests, MaximumActive;
        public int StatusRequests, PrefixBytesBeforeStall, BodyChunkDelayMs;
        public long AdvertisedLength = 5;
        public bool WaitBeforeHeaders;
        private int active;
        public string Status = "200 OK", EmptyId;
        public byte[] SentBody = Body;
        public Fixture()
        {
            listener = new TcpListener(IPAddress.Loopback, 0); listener.Start(); Port = ((IPEndPoint)listener.LocalEndpoint).Port;
            Task accept = Accept();
        }
        private async Task Accept()
        {
            while (true)
            {
                TcpClient client; try { client = await listener.AcceptTcpClientAsync(); } catch (Exception) { return; }
                Task work = Task.Run(delegate { return Handle(client); });
            }
        }
        private async Task Handle(TcpClient client)
        {
            bool counted = false;
            try
            {
                using (client)
                using (NetworkStream stream = client.GetStream())
                {
                    stream.ReadTimeout = 3000; var header = new StringBuilder();
                    while (header.Length < 8192 && !header.ToString().EndsWith("\r\n\r\n", StringComparison.Ordinal))
                    { int next = stream.ReadByte(); if (next < 0) return; header.Append((char)next); }
                    if (header.ToString().IndexOf("Authorization: Bearer " + Token, StringComparison.OrdinalIgnoreCase) < 0) throw new Exception("Missing fixture credential.");
                    string requestPath = header.ToString().Split(' ')[1];
                    if (requestPath == "/v1/status")
                    {
                        Interlocked.Increment(ref StatusRequests);
                        byte[] json = Encoding.UTF8.GetBytes("{\"version\":1,\"expiresAt\":1900000000000,\"revision\":1,\"items\":[],\"gesture\":{\"id\":\"\",\"revision\":0,\"phase\":\"\",\"itemIds\":[]}}");
                        byte[] ready = Encoding.ASCII.GetBytes("HTTP/1.1 200 OK\r\nContent-Length: " + json.Length + "\r\nConnection: close\r\n\r\n");
                        await stream.WriteAsync(ready, 0, ready.Length); await stream.WriteAsync(json, 0, json.Length); return;
                    }
                    int running = Interlocked.Increment(ref active); counted = true;
                    int previous;
                    do { previous = MaximumActive; if (running <= previous) break; } while (Interlocked.CompareExchange(ref MaximumActive, running, previous) != previous);
                    Interlocked.Increment(ref Requests);
                    string id = requestPath.Substring("/v1/file/".Length);
                    byte[] content = id == EmptyId ? new byte[0] : SentBody;
                    long length = id == EmptyId ? 0 : AdvertisedLength;
                    byte[] response = Encoding.ASCII.GetBytes("HTTP/1.1 " + Status + "\r\nContent-Length: " + length + "\r\nConnection: close\r\n\r\n");
                    if (WaitBeforeHeaders) await Release.Task;
                    await stream.WriteAsync(response, 0, response.Length);
                    int prefix = Math.Min(content.Length, PrefixBytesBeforeStall);
                    if (prefix > 0) await stream.WriteAsync(content, 0, prefix);
                    await Release.Task;
                    // Mark the response ready to finish before its last bytes
                    // let the next bounded worker open a socket.
                    Interlocked.Decrement(ref active); counted = false;
                    if (BodyChunkDelayMs == 0) await stream.WriteAsync(content, prefix, content.Length - prefix);
                    else for (int offset = prefix; offset < content.Length; offset++)
                    { await stream.WriteAsync(content, offset, 1); if (offset + 1 < content.Length) await Task.Delay(BodyChunkDelayMs); }
                }
            }
            catch (Exception) { }
            finally { if (counted) Interlocked.Decrement(ref active); }
        }
        public void Dispose() { Release.TrySetResult(true); listener.Stop(); }
    }
