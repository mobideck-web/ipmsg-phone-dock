    public static int Main()
    {
        root = Path.Combine(Path.GetTempPath(), "ipmsg-preparation-check-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(root);
        try
        {
            Run().GetAwaiter().GetResult();
            Console.WriteLine("RESULT: " + passed + " preparation checks passed. Generated loopback bytes only; no phone, mouse drag, Explorer or UI automation used.");
            return 0;
        }
        catch (Exception error) { Console.Error.WriteLine(error); return 1; }
        finally
        {
            string temporary = Path.GetFullPath(Path.GetTempPath()).TrimEnd('\\') + "\\";
            string owned = Path.GetFullPath(root);
            if (owned.StartsWith(temporary, StringComparison.OrdinalIgnoreCase) && Path.GetFileName(owned).StartsWith("ipmsg-preparation-check-", StringComparison.Ordinal))
                try { Directory.Delete(owned, true); } catch (IOException) { }
        }
    }

    private static async Task Run()
    {
        await BoundedAndShared();
